"""Run the SQL interview questions in sql_practice/ against the warehouse and write the lesson with real outputs.

    python -m olistwh.sqlpractice            # run all, write docs/learn/06_sql_interview_practice.md
    python -m olistwh.sqlpractice 08         # run one question and print the result
"""
from __future__ import annotations

import re
import sys

import pandas as pd

from .ingest import ROOT
from .warehouse import connect

SQL_DIR = ROOT / "sql_practice"
LESSON = ROOT / "docs" / "learn" / "06_sql_interview_practice.md"


def questions() -> list[dict]:
    out = []
    for path in sorted(SQL_DIR.glob("*.sql")):
        text = path.read_text()
        header = {}
        for key in ("Level", "Question", "Concepts", "Takeaway"):
            m = re.search(rf"^-- {key}:(.*?)(?=^-- [A-Z][a-z]+:|^(?!--))", text, re.M | re.S)
            header[key.lower()] = re.sub(r"\s*\n--\s*", " ", m.group(1)).strip() if m else ""
        body = "\n".join(ln for ln in text.splitlines() if not re.match(r"-- (Level|Question|Concepts|Takeaway):", ln))
        body = re.sub(r"^--\s{2,}.*\n", "", body, flags=re.M).strip()  # drop wrapped header lines
        out.append({"id": path.stem[:2], "file": path.name, "sql": body, **header})
    return out


def run(q: dict, con=None) -> pd.DataFrame:
    con = con or connect()
    return con.execute(q["sql"]).df()


def _md_table(df: pd.DataFrame, max_rows: int = 12) -> str:
    shown = df.head(max_rows).copy()
    for c in shown.columns:
        if pd.api.types.is_datetime64_any_dtype(shown[c]):
            shown[c] = shown[c].dt.strftime("%Y-%m-%d")
    md = shown.to_markdown(index=False, floatfmt=",.2f")
    if len(df) > max_rows:
        md += f"\n\n*... {len(df) - max_rows} more rows*"
    return md


def write_lesson() -> int:
    con = connect()
    qs = questions()
    parts = [
        "# 06 · SQL interview practice (22 questions on this warehouse)",
        "",
        "Every query below runs against the built warehouse and the result shown is the real output "
        "(regenerated by `olist sql`). **Try each question yourself first**: open a DuckDB shell with "
        "`duckdb warehouse/olist.duckdb` (or `olist sql 08` to run one file), write your answer, then compare.",
        "",
        "Tables you can use: `core.fct_orders`, `core.fct_order_items`, `core.dim_customers`, `core.dim_products`, "
        "`core.dim_sellers`, `core.dim_date`, and the untouched `raw.*` tables. Column lists: "
        "[warehouse/models/marts/core/_core.yml](../../warehouse/models/marts/core/_core.yml).",
        "",
        "DuckDB extras used here (and their equivalents elsewhere): `QUALIFY` filters on a window function "
        "(Snowflake/BigQuery/Databricks have it; in Postgres/SQL Server wrap the query in a CTE and filter "
        "`where rn = 1`); `count(*) filter (where ...)` is `sum(case when ... then 1 else 0 end)` in any database; "
        "`date_diff('day', a, b)` is `DATEDIFF(day, a, b)` in SQL Server.",
        "",
        "| # | Level | Question | Concepts |", "|---|---|---|---|",
    ]
    for q in qs:
        parts.append(f"| [{q['id']}](#q{q['id']}) | {q['level']} | {q['question']} | {q['concepts']} |")
    for q in qs:
        df = run(q, con)
        parts += ["", f"## Q{q['id']}", f"<a id=\"q{q['id']}\"></a>", "",
                  f"**{q['question']}**  ", f"*Level: {q['level']} · Concepts: {q['concepts']}*", "",
                  "<details><summary>Show answer</summary>", "", "```sql", q["sql"], "```", "",
                  "Result:", "", _md_table(df), ""]
        if q["takeaway"]:
            parts += [f"**Takeaway:** {q['takeaway']}", ""]
        parts += ["</details>"]
    LESSON.parent.mkdir(parents=True, exist_ok=True)
    LESSON.write_text("\n".join(parts) + "\n")
    return len(qs)


def main() -> None:
    pd.set_option("display.width", 160)
    pd.set_option("display.max_columns", 20)
    if len(sys.argv) > 1:
        q = next(q for q in questions() if q["id"] == sys.argv[1].zfill(2))
        print(f"Q{q['id']}: {q['question']}\n")
        print(run(q).to_string(index=False))
        return
    n = write_lesson()
    print(f"ran {n} queries -> {LESSON.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
